import { test } from 'node:test';
import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
import { join } from 'node:path';
import { rc2Root } from '../../src/adapters/kingpin-rc2/load.ts';
import { requestBinding, bindingHash } from '../../src/adapters/kingpin-rc2/approved-restart-binding.ts';
import { runApprovedRestart } from '../../src/adapters/kingpin-rc2/approved-restart.ts';
test('approved review is invalidated by durable capability revocation after graceful process replacement', async () => {
  const result = await runApprovedRestart();
  assert.equal(result.passed, true);
  const record = result.timeline.find(r => r.category === 'governance');
  assert.ok(record?.category === 'governance');
  assert.equal(record.data.result, 'INDETERMINATE');
  const e = record.data.evidence.rc2_approved_restart as any;
  for (const pid of [e.a.pid, e.b.pid]) assert.throws(() => process.kill(pid, 0), (err: any) => err.code === 'ESRCH');
  assert.equal(e.replay.response.status, 403);
  assert.equal(e.replay.response.body.reason, 'CAPABILITY_REVOKED');
  assert.equal(e.replay.response.body.authority_decision, undefined);
  assert.equal(e.replay.review.body.status, 'invalidated');
  const native = await import(pathToFileURL(join(rc2Root, 'kingpin/review/model.js')).href);
  const audit = await import(pathToFileURL(join(rc2Root, 'kingpin/audit/events.js')).href);
  assert.deepEqual(requestBinding(e.replay.body, e.a.identity.principal), native.requestBinding(e.replay.body, e.a.identity.principal));
  assert.equal(bindingHash(e.replay.nativeBinding), audit.bindingHash(e.replay.nativeBinding));
  native.validateReviewTransition(e.first.approval.body.review, e.replay.review.body);
  assert.deepEqual(e.final.observer.map((r: any) => [r.type, r.pid]), [['ready', e.a.pid], ['ready', e.b.pid]]);
  assert.deepEqual(e.provenance.runtime, e.provenance.runtimeAfterB);
  assert.equal(e.provenance.runtime.source, 'repository-source');
  assert.deepEqual(e.final.ledger, []); assert.deepEqual(e.final.calls, []); assert.equal(e.final.file.exists, false);
});
